// Seeded random numbers for Tilly's Great Thanksgiving Escape.
// The world is spawned from one deterministic stream so a screenshot run
// (?shot=play&seed=7) renders the exact same farm every time, while a
// normal run seeds from the clock and never repeats itself.

export function makeRng(seed) {
  // mulberry32: a tiny, fast, well-behaved seeded generator.
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function range(rng, min, max) {
  return min + rng() * (max - min);
}

export function pick(rng, list) {
  return list[Math.floor(rng() * list.length)];
}

export function chance(rng, p) {
  return rng() < p;
}

// A one-off shuffle helper used for the title screen's floating feathers.
export function shuffle(rng, list) {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
